#!/usr/bin/env python3
"""
Chart Generator for Cache Benchmark Results
Project 7 - 2-Way Set-Associative vs Direct-Mapped Cache
Owner: Member 4 (Traces, Comparison Testbench, Scripts)

Reads results/results.csv (generated by tb_compare.v) and produces:
  1. results/hit_rate.png   - Grouped bar chart comparing hit rates per trace.
  2. results/cycles.png     - Grouped bar chart comparing total cycles per trace.

Phase II additions (Member 4):
  3. results/sweep_rd_lat.png  - Line chart: hit rate vs RD_LAT sweep (from Member 3 CSVs).
  4. results/sweep_wr_lat.png  - Line chart: cycles vs WR_LAT sweep (from Member 3 CSVs).

Usage:
    python3 scripts/plot_results.py                    # uses results/results.csv
    python3 scripts/plot_results.py path/to/results.csv  # custom CSV path
"""

import os
import sys
import csv

# ---------------------------------------------------------------------------
# Resolve project root (scripts/ is one level below)
# ---------------------------------------------------------------------------
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
RESULTS_DIR = os.path.join(REPO_ROOT, "results")

# ---------------------------------------------------------------------------
# Parse CSV
# ---------------------------------------------------------------------------
def load_results(csv_path):
    """
    Reads results.csv and returns two parallel dicts keyed by trace name:
      hit_rates = { trace: { '2way': float, 'direct': float } }
      cycles    = { trace: { '2way': int,   'direct': int   } }
    Preserves insertion order (first-seen trace order in CSV).
    """
    hit_rates = {}
    cycles = {}

    with open(csv_path, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            trace   = row["trace"]
            design  = row["design"]
            hr      = float(row["hit_rate"])
            cy      = int(row["cycles"])

            if trace not in hit_rates:
                hit_rates[trace] = {}
                cycles[trace] = {}

            hit_rates[trace][design] = hr
            cycles[trace][design]    = cy

    return hit_rates, cycles


# ---------------------------------------------------------------------------
# Plotting
# ---------------------------------------------------------------------------
def make_charts(hit_rates, cycles, output_dir):
    """
    Generates two grouped bar charts and saves them as PNG files.
    Uses matplotlib with the 'Agg' backend for headless rendering.
    """
    import matplotlib
    matplotlib.use("Agg")  # non-interactive backend for headless environments
    import matplotlib.pyplot as plt
    import numpy as np

    traces = list(hit_rates.keys())
    n = len(traces)
    x = np.arange(n)
    width = 0.35

    # --- Chart 1: Hit Rate Comparison ---
    hr_2way   = [hit_rates[t].get("2way", 0.0)   for t in traces]
    hr_direct = [hit_rates[t].get("direct", 0.0) for t in traces]

    fig1, ax1 = plt.subplots(figsize=(max(10, n * 1.2), 6))
    bars1a = ax1.bar(x - width / 2, hr_2way,   width, label="2-Way LRU",
                     color="#2196F3", edgecolor="white", linewidth=0.8)
    bars1b = ax1.bar(x + width / 2, hr_direct, width, label="Direct-Mapped",
                     color="#FF9800", edgecolor="white", linewidth=0.8)

    ax1.set_xlabel("Trace Workload", fontsize=12)
    ax1.set_ylabel("Hit Rate (%)", fontsize=12)
    ax1.set_title("Cache Hit Rate Comparison: 2-Way LRU vs Direct-Mapped",
                  fontsize=14, fontweight="bold")
    ax1.set_xticks(x)
    ax1.set_xticklabels(traces, rotation=30, ha="right", fontsize=10)
    ax1.set_ylim(0, 105)
    ax1.legend(fontsize=11, loc="upper right")
    ax1.grid(axis="y", alpha=0.3)

    # Add value labels on bars
    for bar in bars1a:
        h = bar.get_height()
        if h > 0:
            ax1.annotate(f"{h:.1f}%", xy=(bar.get_x() + bar.get_width() / 2, h),
                         xytext=(0, 3), textcoords="offset points",
                         ha="center", va="bottom", fontsize=8)
    for bar in bars1b:
        h = bar.get_height()
        if h > 0:
            ax1.annotate(f"{h:.1f}%", xy=(bar.get_x() + bar.get_width() / 2, h),
                         xytext=(0, 3), textcoords="offset points",
                         ha="center", va="bottom", fontsize=8)

    fig1.tight_layout()
    hit_rate_path = os.path.join(output_dir, "hit_rate.png")
    fig1.savefig(hit_rate_path, dpi=150)
    plt.close(fig1)
    print(f"Saved: {hit_rate_path}")

    # --- Chart 2: Total Cycles Comparison ---
    cy_2way   = [cycles[t].get("2way", 0)   for t in traces]
    cy_direct = [cycles[t].get("direct", 0) for t in traces]

    fig2, ax2 = plt.subplots(figsize=(max(10, n * 1.2), 6))
    bars2a = ax2.bar(x - width / 2, cy_2way,   width, label="2-Way LRU",
                     color="#4CAF50", edgecolor="white", linewidth=0.8)
    bars2b = ax2.bar(x + width / 2, cy_direct, width, label="Direct-Mapped",
                     color="#F44336", edgecolor="white", linewidth=0.8)

    ax2.set_xlabel("Trace Workload", fontsize=12)
    ax2.set_ylabel("Total Execution Cycles", fontsize=12)
    ax2.set_title("Total Cycle Count Comparison: 2-Way LRU vs Direct-Mapped",
                  fontsize=14, fontweight="bold")
    ax2.set_xticks(x)
    ax2.set_xticklabels(traces, rotation=30, ha="right", fontsize=10)
    ax2.legend(fontsize=11, loc="upper right")
    ax2.grid(axis="y", alpha=0.3)

    # Add value labels on bars
    for bar in bars2a:
        h = bar.get_height()
        if h > 0:
            ax2.annotate(f"{h:,}", xy=(bar.get_x() + bar.get_width() / 2, h),
                         xytext=(0, 3), textcoords="offset points",
                         ha="center", va="bottom", fontsize=7)
    for bar in bars2b:
        h = bar.get_height()
        if h > 0:
            ax2.annotate(f"{h:,}", xy=(bar.get_x() + bar.get_width() / 2, h),
                         xytext=(0, 3), textcoords="offset points",
                         ha="center", va="bottom", fontsize=7)

    fig2.tight_layout()
    cycles_path = os.path.join(output_dir, "cycles.png")
    fig2.savefig(cycles_path, dpi=150)
    plt.close(fig2)
    print(f"Saved: {cycles_path}")


