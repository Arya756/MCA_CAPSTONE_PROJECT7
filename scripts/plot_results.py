def make_sweep_charts(results_dir):
    """
    Phase II (Member 4): generate line charts from Member 3's latency-sweep CSVs.
    If the CSVs do not exist yet, this function silently skips.

    Expected CSV formats (produced by scripts/run_latency_study.sh):
      results/latency_rd<N>.csv  with columns: trace,design,hit_rate,cycles
      results/latency_wr<N>.csv  with columns: trace,design,hit_rate,cycles
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # Discover all RD_LAT sweep files
    rd_files = sorted([
        f for f in os.listdir(results_dir)
        if f.startswith("latency_rd") and f.endswith(".csv")
    ])
    wr_files = sorted([
        f for f in os.listdir(results_dir)
        if f.startswith("latency_wr") and f.endswith(".csv")
    ])

    def extract_latency(filename, prefix):
        """Extract numeric latency from filename like 'latency_rd8.csv' -> 8."""
        try:
            return int(filename.replace(prefix, "").replace(".csv", ""))
        except ValueError:
            return -1

    # ---- RD_LAT sweep: total cycles across all traces per latency setting ----
    if len(rd_files) >= 2:
        lat_vals_rd = []
        totcycles_2w = []
        totcycles_dir = []

        for fname in rd_files:
            lat = extract_latency(fname, "latency_rd")
            if lat < 0:
                continue
            csv_path = os.path.join(results_dir, fname)
            hr, cy = load_results(csv_path)
            total_2w  = sum(cy[t].get("2way", 0)   for t in cy)
            total_dir = sum(cy[t].get("direct", 0) for t in cy)
            lat_vals_rd.append(lat)
            totcycles_2w.append(total_2w)
            totcycles_dir.append(total_dir)

        # Sort by latency value
        combined = sorted(zip(lat_vals_rd, totcycles_2w, totcycles_dir))
        lat_vals_rd, totcycles_2w, totcycles_dir = zip(*combined)

        fig, ax = plt.subplots(figsize=(8, 5))
        ax.plot(lat_vals_rd, totcycles_2w,  "o-", color="#2196F3", linewidth=2,
                markersize=7, label="2-Way LRU")
        ax.plot(lat_vals_rd, totcycles_dir, "s--", color="#FF9800", linewidth=2,
                markersize=7, label="Direct-Mapped")
        ax.set_xlabel("Read Latency RD_LAT (cycles)", fontsize=12)
        ax.set_ylabel("Total Cycles (all traces)", fontsize=12)
        ax.set_title("Sensitivity to Read Miss Penalty (RD_LAT Sweep)",
                     fontsize=13, fontweight="bold")
        ax.set_xticks(lat_vals_rd)
        ax.legend(fontsize=11)
        ax.grid(alpha=0.3)
        fig.tight_layout()
        path = os.path.join(results_dir, "sweep_rd_lat.png")
        fig.savefig(path, dpi=150)
        plt.close(fig)
        print(f"Saved: {path}")

    # ---- WR_LAT sweep: total cycles across all traces per latency setting ----
    if len(wr_files) >= 2:
        lat_vals_wr = []
        totcycles_2w = []
        totcycles_dir = []

        for fname in wr_files:
            lat = extract_latency(fname, "latency_wr")
            if lat < 0:
                continue
            csv_path = os.path.join(results_dir, fname)
            hr, cy = load_results(csv_path)
            total_2w  = sum(cy[t].get("2way", 0)   for t in cy)
            total_dir = sum(cy[t].get("direct", 0) for t in cy)
            lat_vals_wr.append(lat)
            totcycles_2w.append(total_2w)
            totcycles_dir.append(total_dir)

        combined = sorted(zip(lat_vals_wr, totcycles_2w, totcycles_dir))
        lat_vals_wr, totcycles_2w, totcycles_dir = zip(*combined)

        fig, ax = plt.subplots(figsize=(8, 5))
        ax.plot(lat_vals_wr, totcycles_2w,  "o-", color="#4CAF50", linewidth=2,
                markersize=7, label="2-Way LRU")
        ax.plot(lat_vals_wr, totcycles_dir, "s--", color="#F44336", linewidth=2,
                markersize=7, label="Direct-Mapped")
        ax.set_xlabel("Write Latency WR_LAT (cycles)", fontsize=12)
        ax.set_ylabel("Total Cycles (all traces)", fontsize=12)
        ax.set_title("Sensitivity to Write-Through Penalty (WR_LAT Sweep)",
                     fontsize=13, fontweight="bold")
        ax.set_xticks(lat_vals_wr)
        ax.legend(fontsize=11)
        ax.grid(alpha=0.3)
        fig.tight_layout()
        path = os.path.join(results_dir, "sweep_wr_lat.png")
        fig.savefig(path, dpi=150)
        plt.close(fig)
        print(f"Saved: {path}")


def main():
    # Accept optional CSV path as argument; default to results/results.csv
    if len(sys.argv) > 1:
        csv_path = sys.argv[1]
    else:
        csv_path = os.path.join(RESULTS_DIR, "results.csv")

    if not os.path.isfile(csv_path):
        print(f"ERROR: Results CSV not found: {csv_path}")
        print("Run ./scripts/run_all.sh first to generate results/results.csv.")
        sys.exit(1)

    print(f"Reading results from: {csv_path}")
    hit_rates, cycles = load_results(csv_path)
    print(f"Found {len(hit_rates)} trace workloads: {', '.join(hit_rates.keys())}")

    os.makedirs(RESULTS_DIR, exist_ok=True)
    make_charts(hit_rates, cycles, RESULTS_DIR)

    # Phase II: generate sweep charts if Member 3's CSVs are present
    make_sweep_charts(RESULTS_DIR)

    print("\nChart generation complete!")
    print(f"  - Hit Rate Chart:  results/hit_rate.png")
    print(f"  - Cycles Chart:    results/cycles.png")
    print(f"  - Sweep charts:    results/sweep_rd_lat.png, results/sweep_wr_lat.png (if CSVs present)")


if __name__ == "__main__":
    main()

